const DICT: Record<Lang, Record<keyof typeof ZH, string>> = { zh: ZH, en: EN, ja: JA, ko: KO };

let current: Lang = "zh";

export function isLang(v: unknown): v is Lang {
  return v === "zh" || v === "en" || v === "ja" || v === "ko";
}

export function getLang(): Lang {
  return current;
}

export function setGlobalLang(lang: Lang) {
  current = lang;
}

export function t(key: keyof typeof ZH, lang: Lang = current): string {
  return DICT[lang][key];
}

export function categoryLabel(cat: Category, lang: Lang) {
  return t(cat, lang);
}

